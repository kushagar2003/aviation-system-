-- Avatition database, version 2 (fresh start).
-- Run this file FIRST on an empty database. Then run 02_data.sql.
--
-- Tables:
--   cities     3 rows   Delhi, Mumbai, Bengaluru
--   airports   3 rows   one airport per city (linked to cities)
--   companies  10 rows  the private aviation companies (linked to cities)
--   flights    10 rows  commercial and private flights (linked to airports and companies)
--
-- These are plain CREATE TABLE statements on purpose: on a database that already
-- has tables with these names, they stop with an error instead of silently
-- changing anything. To start over on a test database, run the DROP block at the bottom first.

CREATE TABLE cities (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    TEXT NOT NULL UNIQUE
);

CREATE TABLE airports (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    TEXT NOT NULL UNIQUE,                         -- airport code, e.g. VIDP
    name    TEXT NOT NULL,
    city_id INTEGER NOT NULL REFERENCES cities(id)
);

CREATE TABLE companies (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_code        TEXT NOT NULL UNIQUE,             -- e.g. IND-001
    name                TEXT NOT NULL,
    phone               TEXT NOT NULL,                    -- 'Not publicly listed' when the company publishes none
    email               TEXT NOT NULL,                    -- 'Not publicly listed' when the company publishes none
    website             TEXT NOT NULL,
    city_id             INTEGER NOT NULL REFERENCES cities(id),   -- head office city
    hq_country          TEXT NOT NULL DEFAULT 'India',
    operating_locations TEXT[] NOT NULL DEFAULT '{}',     -- airports / cities where the company operates
    regions_served      TEXT[] NOT NULL DEFAULT '{}',     -- e.g. India, International
    categories          TEXT[] NOT NULL DEFAULT '{}',     -- charter, operator, aircraft_management, broker, fbo, support
    services            TEXT[] NOT NULL DEFAULT '{}',
    customer_segments   TEXT[] NOT NULL DEFAULT '{}',     -- corporate, medical, government, ...
    verified_fleet      TEXT[] NOT NULL DEFAULT '{}',     -- 'Not publicly verified' when no public source lists the fleet
    description         TEXT,
    verification_status TEXT NOT NULL DEFAULT 'unverified'
                        CHECK (verification_status IN ('high', 'medium', 'low', 'unverified')),
    verified_at         DATE NOT NULL,                    -- when the facts were last checked against the sources
    source_urls         TEXT[] NOT NULL DEFAULT '{}'      -- where the facts above came from
);

CREATE TABLE flights (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number         TEXT NOT NULL UNIQUE,
    flight_type           TEXT NOT NULL CHECK (flight_type IN ('private_charter', 'commercial')),
    company_id            INTEGER REFERENCES companies(id),  -- set for private charter flights only
    carrier_name          TEXT,                              -- set for commercial flights only
    departure_airport_id  INTEGER NOT NULL REFERENCES airports(id),
    arrival_airport_id    INTEGER NOT NULL REFERENCES airports(id),
    departure_time        TIMESTAMPTZ NOT NULL,
    arrival_time          TIMESTAMPTZ NOT NULL,
    aircraft_type         TEXT NOT NULL,
    seats_available       INTEGER NOT NULL CHECK (seats_available >= 0),
    price_inr             INTEGER NOT NULL CHECK (price_inr > 0),
    price_basis           TEXT NOT NULL CHECK (price_basis IN ('per_flight', 'per_seat')),
    status                TEXT NOT NULL DEFAULT 'scheduled'
                          CHECK (status IN ('scheduled', 'cancelled', 'full')),

    CHECK (departure_airport_id <> arrival_airport_id),
    CHECK (arrival_time > departure_time),
    -- A private flight belongs to one of our companies. A commercial flight has a carrier name instead.
    CHECK (
        (flight_type = 'private_charter' AND company_id IS NOT NULL AND carrier_name IS NULL)
        OR
        (flight_type = 'commercial' AND company_id IS NULL AND carrier_name IS NOT NULL)
    )
);

CREATE INDEX idx_flights_route_time ON flights (departure_airport_id, arrival_airport_id, departure_time);
CREATE INDEX idx_flights_company ON flights (company_id);
CREATE INDEX idx_airports_city ON airports (city_id);
CREATE INDEX idx_companies_city ON companies (city_id);

